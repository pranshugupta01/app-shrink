app.notFound((c) => c.json({ error: 'Not Found', path: new URL(c.req.url).pathname }, 404));

app.onError((error, c) => {
  console.error('[app-shrink] unhandled error:', error);
  return c.json({ error: 'Internal Server Error', message: String(error && error.message ? error.message : error) }, 500);
});

// ===========================================================================
